package com.blueprintai.export;

import com.blueprintai.architecture.ArchitectureGraph;
import com.blueprintai.architecture.ArchitectureGraphAiOutput;
import com.blueprintai.architecture.ArchitectureGraphRepository;
import com.blueprintai.blueprint.Blueprint;
import com.blueprintai.blueprint.BlueprintRepository;
import com.blueprintai.feature.Feature;
import com.blueprintai.feature.FeatureRepository;
import com.blueprintai.learning.Concept;
import com.blueprintai.learning.ConceptRepository;
import com.blueprintai.learning.GlossaryTerm;
import com.blueprintai.learning.GlossaryTermRepository;
import com.blueprintai.milestone.Milestone;
import com.blueprintai.milestone.MilestoneRepository;
import com.blueprintai.project.Project;
import com.blueprintai.project.ProjectRepository;
import com.blueprintai.stack.StackChoice;
import com.blueprintai.stack.StackChoiceRepository;
import com.blueprintai.stack.StackRecommendAiOutput;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.*;

@Service
@RequiredArgsConstructor
public class ExportService {

    private final ProjectRepository projectRepository;
    private final BlueprintRepository blueprintRepository;
    private final FeatureRepository featureRepository;
    private final ArchitectureGraphRepository architectureGraphRepository;
    private final StackChoiceRepository stackChoiceRepository;
    private final MilestoneRepository milestoneRepository;
    private final GlossaryTermRepository glossaryTermRepository;
    private final ConceptRepository conceptRepository;
    private final ObjectMapper objectMapper;

    @Transactional(readOnly = true)
    public String generateMarkdownHandbook(UUID projectId) {
        Project project = projectRepository.findById(projectId)
                .orElseThrow(() -> new IllegalArgumentException("Project not found: " + projectId));

        Optional<Blueprint> blueprintOpt = blueprintRepository.findTopByProjectIdOrderByVersionDesc(projectId);
        List<Feature> features = featureRepository.findAllByProjectIdOrderByCreatedAtAsc(projectId);
        Optional<ArchitectureGraph> archOpt = architectureGraphRepository.findTopByProjectIdOrderByVersionDesc(projectId);
        List<StackChoice> stackChoices = stackChoiceRepository.findByProjectIdOrderByCreatedAtAsc(projectId);
        List<Milestone> milestones = milestoneRepository.findByProjectIdOrderByOrderIndexAsc(projectId);
        List<GlossaryTerm> glossary = glossaryTermRepository.findAll();
        List<Concept> concepts = conceptRepository.findAll();

        StringBuilder sb = new StringBuilder();
        DateTimeFormatter dtf = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm").withZone(ZoneId.of("UTC"));

        // 1. Header
        Instant createdAt = project.getCreatedAt() != null ? project.getCreatedAt() : java.time.Instant.now();
        sb.append("# ").append(project.getTitle()).append(" - Architecture & Build Handbook\n\n");
        sb.append("> Generated by **BlueprintAI** on ")
          .append(dtf.format(createdAt))
          .append(" UTC | Target Platform: `").append(project.getTargetPlatform()).append("`\n\n");

        sb.append("## 1. Project Overview\n\n");
        sb.append("- **Core Idea:** ").append(project.getIdeaText()).append("\n");
        sb.append("- **Audience Level:** ").append(project.getUser() != null ? project.getUser().getLevel() : "BEGINNER").append("\n");
        sb.append("- **Status:** ").append(project.getStatus()).append("\n\n");
        sb.append("---\n\n");

        // 2. Architecture Diagram (Mermaid)
        sb.append("## 2. System Architecture Diagram\n\n");
        sb.append("```mermaid\ngraph TD\n");
        if (archOpt.isPresent()) {
            List<ArchitectureGraphAiOutput.GraphNodeItem> nodes = List.of();
            List<ArchitectureGraphAiOutput.GraphEdgeItem> edges = List.of();
            try {
                nodes = objectMapper.readValue(archOpt.get().getNodes(), new TypeReference<>() {});
                edges = objectMapper.readValue(archOpt.get().getEdges(), new TypeReference<>() {});
            } catch (Exception ignored) {}

            if (!nodes.isEmpty()) {
                Map<String, String> nodeLabels = new HashMap<>();
                for (ArchitectureGraphAiOutput.GraphNodeItem node : nodes) {
                    String safeId = node.id().replaceAll("[^a-zA-Z0-9_]", "_");
                    nodeLabels.put(node.id(), safeId);
                    sb.append("    ").append(safeId)
                      .append("[\"").append(node.label()).append("<br/><em>(").append(node.layer()).append(")</em>\"]\n");
                }

                for (ArchitectureGraphAiOutput.GraphEdgeItem edge : edges) {
                    String src = nodeLabels.getOrDefault(edge.from(), edge.from().replaceAll("[^a-zA-Z0-9_]", "_"));
                    String tgt = nodeLabels.getOrDefault(edge.to(), edge.to().replaceAll("[^a-zA-Z0-9_]", "_"));
                    String label = (edge.label() != null && !edge.label().isBlank()) ? ("| " + edge.label() + " |") : "";
                    sb.append("    ").append(src).append(" -->").append(label).append(" ").append(tgt).append("\n");
                }
            } else {
                renderDefaultMermaid(sb);
            }
        } else {
            renderDefaultMermaid(sb);
        }
        sb.append("```\n\n---\n\n");

        // 3. Tech Stack Decisions
        sb.append("## 3. Technology Stack & Architectural Decisions\n\n");
        if (stackChoices.isEmpty()) {
            sb.append("*No customized stack decisions recorded yet.*\n\n");
        } else {
            for (StackChoice sc : stackChoices) {
                sb.append("### ").append(sc.getLayer()).append(" Layer\n\n");
                sb.append("- **Recommended Technology:** `").append(sc.getRecommended()).append("`\n");
                sb.append("- **Chosen by Builder:** `").append(sc.getUserChoice() != null ? sc.getUserChoice() : sc.getRecommended()).append("`\n");
                sb.append("- **Architectural Reasoning:** ").append(sc.getReasoning()).append("\n\n");

                List<StackRecommendAiOutput.StackAlternativeItem> alts = List.of();
                try {
                    alts = objectMapper.readValue(sc.getAlternatives(), new TypeReference<>() {});
                } catch (Exception ignored) {}

                if (!alts.isEmpty()) {
                    sb.append("**Considered Alternatives:**\n\n");
                    for (StackRecommendAiOutput.StackAlternativeItem alt : alts) {
                        sb.append("- **").append(alt.name()).append(":** ");
                        if (alt.whenBetter() != null) {
                            sb.append("When better: ").append(alt.whenBetter());
                        }
                        sb.append("\n");
                    }
                    sb.append("\n");
                }
            }
        }
        sb.append("---\n\n");

        // 4. Features & Data Entities
        sb.append("## 4. Feature Specifications\n\n");
        if (features.isEmpty()) {
            sb.append("*No features generated yet.*\n\n");
        } else {
            int idx = 1;
            for (Feature feat : features) {
                sb.append("### ").append(idx++).append(". ").append(feat.getName());
                if (feat.getPriority() != null) {
                    sb.append(" `[").append(feat.getPriority()).append("]`");
                }
                sb.append("\n\n");
                sb.append(feat.getDescription()).append("\n\n");

                if (feat.getScreens() != null && !feat.getScreens().equals("[]")) {
                    sb.append("- **Screens / UI Components:** `").append(feat.getScreens()).append("`\n");
                }
                if (feat.getDataEntities() != null && !feat.getDataEntities().equals("[]")) {
                    sb.append("- **Data Entities:** `").append(feat.getDataEntities()).append("`\n");
                }
                if (feat.getLogicNotes() != null && !feat.getLogicNotes().isBlank()) {
                    sb.append("- **Logic & Guardrails:** ").append(feat.getLogicNotes()).append("\n");
                }
                sb.append("\n");
            }
        }
        sb.append("---\n\n");

        // 5. Guided Build Milestones
        sb.append("## 5. Guided Build Roadmap & Learning Milestones\n\n");
        if (milestones.isEmpty()) {
            sb.append("*No milestones generated yet.*\n\n");
        } else {
            for (Milestone m : milestones) {
                sb.append("### Milestone ").append(m.getOrderIndex()).append(": ").append(m.getTitle());
                sb.append(" `[").append(m.getStatus()).append("]`\n\n");
                sb.append(m.getDescription()).append("\n\n");
                if (m.getConcepts() != null && !m.getConcepts().isEmpty()) {
                    sb.append("**Key Concepts to Understand:**\n");
                    for (String c : m.getConcepts()) {
                        sb.append("- ").append(c).append("\n");
                    }
                    sb.append("\n");
                }
            }
        }
        sb.append("---\n\n");

        // 6. Glossary & Core Concepts
        sb.append("## 6. Architecture Glossary & Concept Cheatsheet\n\n");
        sb.append("| Term | Definition | Real-World Analogy |\n");
        sb.append("| --- | --- | --- |\n");
        for (GlossaryTerm term : glossary) {
            String def = term.getDefinition().replace("|", "\\|");
            String analogy = (term.getAnalogy() != null ? term.getAnalogy().replace("|", "\\|") : "-");
            sb.append("| **").append(term.getTerm()).append("** | ").append(def).append(" | ").append(analogy).append(" |\n");
        }

        sb.append("\n\n---\n*Generated by BlueprintAI - Understand While You Build*\n");
        return sb.toString();
    }

    private void renderDefaultMermaid(StringBuilder sb) {
        sb.append("    Client[\"Frontend (Next.js App Router)\"] -->|HTTP/REST with JWT| API[\"Backend (Spring Boot 3)\"]\n");
        sb.append("    API -->|JPA/SQL| DB[(\"PostgreSQL Database\")]\n");
        sb.append("    API -->|API Key| Grok[\"xAI Grok API (grok-2-latest)\"]\n");
    }
}
