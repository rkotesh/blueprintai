import React from "react";
import { render, screen, waitFor, fireEvent } from "@testing-library/react";
import { describe, it, expect, vi } from "vitest";
import ExportPage from "../app/(app)/projects/[id]/export/page";

const { mockMarkdown } = vi.hoisted(() => {
  const mockMarkdown = `# EventCloud - Architecture & Build Handbook

> Generated by **BlueprintAI** on 2026-11-18 01:00 UTC | Target Platform: \`WEB\`

## 1. Project Overview
- **Core Idea:** A ticket management system for conferences

## 2. System Architecture Diagram
\`\`\`mermaid
graph TD
    Client["Frontend (Next.js App Router)"] --> API["Backend (Spring Boot 3)"]
\`\`\`
`;
  return { mockMarkdown };
});

vi.mock("next/navigation", () => ({
  useParams: () => ({ id: "proj-123" }),
  useRouter: () => ({ push: vi.fn() }),
}));

vi.mock("@/lib/api", () => ({
  api: {
    getHandbookPreview: vi.fn().mockResolvedValue({ markdown: mockMarkdown }),
    getHandbookDownloadUrl: vi.fn().mockReturnValue("http://localhost:8080/api/projects/proj-123/export/handbook.md"),
  },
}));

describe("ExportPage", () => {
  it("renders offline handbook preview and copy/download controls", async () => {
    render(<ExportPage />);

    expect(screen.getByText("Compiling offline architecture handbook...")).toBeInTheDocument();

    await waitFor(() => {
      expect(screen.getByText("Offline Architecture & Build Handbook")).toBeInTheDocument();
      expect(screen.getByText(/blueprint-handbook\.md Preview/i)).toBeInTheDocument();
      expect(screen.getByText(/EventCloud - Architecture & Build Handbook/i)).toBeInTheDocument();
    });

    // Test copy button
    const copyBtn = screen.getByText("Copy Markdown");
    expect(copyBtn).toBeInTheDocument();

    // Test download button
    const downloadBtn = screen.getByText("Download .md File");
    expect(downloadBtn).toBeInTheDocument();
  });
});
